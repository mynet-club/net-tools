// Package routing 是 llmproxy 3.0 的智能路由规划器（工作包 D）。
//
// 分层职责见 docs/3.0-agent-playbook.md §3.D：能力匹配、成本/延迟/区域/数据策略约束、
// provider-model 候选排序、fallback 计划、决策解释。输入输出可序列化、可确定性回放（§2.8）。
//
// # 三条「本包不拥有」的规则
//
// 规划器是**纯函数**：不查数据库、不联网、不读配置文件、不读时钟。所有可变状态
// （健康位、冷却到期点、粘性、价目、观测延迟、gate 结论）都由调用方作为数据传进来。
// 之所以必须这样，是因为 internal/router 把权重随机和熔断状态混在一个可变对象里，
// 一次线上决策事后无法复现；D 存在的意义就是把「决策」和「状态」拆开。
//
//  1. **档序不归 D**（手册 §5「禁止跨包复制业务规则」）。现网的 8 档次序
//     （自有点名 → 系统点名 → 自有兜底 → 系统兜底，各自再分健康/全部）由接线方
//     计算成 Offer.Tier 传进来（小者优先）。D 若再写一遍 priorityTiers，就有了第二个
//     事实源，两边迟早走偏。
//  2. **「这次能不能用这家」不归 D**。D 只问注入的 Gate（调用方用 policy.Resolver 实现）。
//     §3.D 明文禁止绕过 policy resolver，所以 D 内部不出现任何权限规则；被 Gate 拒掉的
//     候选绝不进 Fallbacks，只进 Rejections。
//  3. **数据分级、区域、TTL 的口径来自 policy**：区域走 PolicyContext.RegionAllowed，
//     分级走候选自带的 MaxDataLevel 与 ctx.DataLevel 比较，版本串必须来自实际加载的
//     策略包（由调用方传入，D 不拼）。
//
// # 成本
//
// 无价目的 provider **不当零成本**（§3.D）：cheapest 目标函数默认直接把 CostKnown=false
// 的候选排除（原因码 candidate_cost_unknown）；显式允许未知成本时它们参与排序但被
// 「有无价目」这一层压在档序之前，因此不会占首选位。
//
// # 抽样
//
// 线上模式用调用方注入的 RandomSource（保持现网权重随机的流量分布不变）；
// 回放模式用 SeededSource(seed)（sha256 + splitmix64，跨 Go 版本与跨语言可复现）。
// **禁用 math/rand 全局源**：它既不可复现也不可并发（Go 1.20+ 全局源虽可用，
// 但任何一次外部 Seed 都会把历史审计作废）。
// 粘性命中优先于随机，且命中时**不消耗随机数** —— 否则同一次决策在「有没有记到 seed」
// 两种情况下会走出不同的后续随机序列，回放就永远对不上。
