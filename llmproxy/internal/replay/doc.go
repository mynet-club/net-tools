// Package replay 落地手册 §2.8 的确定性回放契约，以及 §3.0 的策略版本来源校验（工作包 I）。
//
// 这一包只回答一个问题：**一次已经发生过的决策，换一台机器、换一个时刻，还能不能
// 逐字段复现？** 复现不了就必须指出是哪个字段变了（结构化差异），而不是返回一个 bool。
//
// 三条硬约束：
//
//   - 记录结构里不得出现请求正文、正文摘要、prompt、messages、密钥、凭证、个人信息
//     （§2.8「不需要记录请求正文」+ §2.9 + §5）。字段命名也不许出现 body/raw/token/secret
//     这类词，leak_test.go 用反射和 JSON 键扫描把它变成会失败的断言；
//   - 回放一律 fail_closed：时钟缺失、seed 缺失或非法、策略包不覆盖记录范围、
//     记录结构不合法 —— 全部直接拒绝回放，绝不退回到「随机选一个」或「按 deny 收」；
//   - 一切顺序都是显式稳定排序（范围链、候选 provider、命中规则、差异项），
//     绝不依赖 map 遍历顺序，否则「乱进乱出的同一批记录」会产生不同报告。
//
// 与在线模式的关系（§2.8 的分工）：在线的权重随机不受本包影响；本包的抽样器
// （SamplingAlgo = replay-sampling-v1）只用于**复现**，D 包（internal/routing）合并后
// 主线可以用自己的 Sampler 实现替换默认值，从而保证在线与回放逐位一致。
//
// 本包不做任何外部调用：没有 HTTP、没有数据库、不读配置文件；策略包（BundleSet）与
// 记录都由调用方注入，文件读写只走 io.Reader / io.Writer。
