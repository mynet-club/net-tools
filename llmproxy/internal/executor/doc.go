// Package executor 是 llmproxy 3.0 的执行器抽象层（工作包 F）。
//
// 本包只回答一个问题：**「按这份 Attempt 实际打一次上游，发生了什么？」**
// 远程 OpenAI 兼容上游、本地 Ollama、本地 vLLM 实现同一个 Executor 接口，
// 调用方（接线层 / 未来的 handler）拿到的都是同一个 Attempt → Outcome 形状，
// 换执行器不改调用方代码。
//
// 分层职责见 docs/3.0-agent-playbook.md §3.F。以下三条是「本包不拥有」的东西，
// 每一条都有现成的反面教材（2.x 的 internal/server/forwarder.go 把它们揉在一起，
// 于是换后端就得重写整条链路）：
//
//  1. **执行器绝不写费用**。Outcome 里只有观测到的用量（token 数、缓存拆分、
//     content 字节数），没有金额、没有配额、没有计费归属。计量口径归
//     internal/store：同一份用量在哪条规则下折成多少钱，是账本的事实，不是
//     传输层的事实。执行器一旦顺手算了钱，就会出现第二套计价口径。
//  2. **执行器绝不做权限判断**。能不能用这家、这个正文能不能出境，是
//     internal/policy（A 包）与 internal/routing（D 包）在规划期已经结论化的事；
//     执行器收到的 Attempt 就是「已被批准的计划的一次落地」。它在任何分支里
//     都不得拒绝执行一个「看起来不该执行」的请求 —— 那是越权判定，不是它的数据。
//     唯一例外是**目标约束**（scheme / 内嵌凭证 / 路径合法性）：那是传输层自己的
//     安全边界，不是业务权限。
//  3. **执行器绝不写审计表**。它连数据库句柄都不持有。观测结果通过返回值交还，
//     由接线层决定记什么、进哪张表。
//
// # 包的契约（实现必须逐条满足）
//
//   - **无状态，可并发复用**。Executor 实例不持有 per-request 可变状态；
//     一个实例可以同时服务任意多个 goroutine。熔断计数、冷却、粘性都不在
//     本包（它们是 D 的输入数据，由调用方维护）。
//   - **所有外部调用必须带超时、响应体上限和目标约束**（手册 §5）。这三样来自
//     Attempt 的显式字段，绝不以「不限」为默认值 —— 无超时的上游调用是一次挂起的
//     连接池事故，无上限的响应体读是一次 OOM。
//     唯一合法的「不限」写法是**显式声明 0，且同时声明 IsStream**（2026-10-04 裁决，
//     docs/3.0-decision-packages.md 第 2 条）：流式的总时限由调用方 ctx 持有（现网是
//     空闲看门狗），缓冲由逐段透传结构性地排除，这两条都不是「忘了填」。
//     Validate 是这道闸门的唯一入口，非流式拿到 0 一律拒。
//   - **失败方向显式**。本包一律 fail_closed：目标非法、体积超限、流被掐断，
//     都作为明确错误返回，调用方拿不到「半截成功」。是否 fail_open（比如
//     截断流照记 usage）是策略问题，判断权在调用方，本包只把事实标清楚。
//   - **正文只在 Outcome.Body 这条流里存在**。Attempt 的请求体是调用方传入的
//     短生命周期切片，本包不复制进任何导出结构、不序列化、不打日志；
//     响应体原样透传（字节不改），不落 Outcome 的任何字段。
//     观测（usage / content 字节数）是旁路扫描出的**数字**，见 §2.9：
//     「不存原文，不碰隐私」。
//   - **报错文本不含密钥、正文、上游响应体片段**。底层错误只挂在 Cause 上供
//     errors.Is/As 使用，Error() 输出全部由稳定码与稳定 ID 拼装（errors.go）。
//
// # 与相邻包的边界
//
// internal/routing 的 RoutingPlan 给出「用哪个执行器、哪个上游模型」；本包的
// AttemptFromPlan 是消费它的胶水。internal/dialer 负责实际拨号与出网校验，
// 本包从不构造裸 http.DefaultTransport。internal/policy 拥有权限原因码，
// 本包拥有传输失败码 —— 两个轴，互不注册（见 reasons.go 顶部的说明）。
